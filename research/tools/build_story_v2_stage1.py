def find_message_id(turn, quote):
    for i, (role, text, ts) in enumerate(turn["messages"]):
        if quote in text:
            return "m%d" % i
    return None


def resolve_fact(story, fact, turns_by_id):
    src = fact["source"]
    if src["kind"] == "message":
        turn = turns_by_id[src["case_id"]]
        mid = find_message_id(turn, src["quote"])
        if mid is None:
            raise SystemExit("%s: quote not found in %s: %r" % (
                story["id"], src["case_id"], src["quote"]))
        return {"kind": "message", "case_id": public_case(src["case_id"]),
                "message_id": mid, "quote": src["quote"]}
    if src["kind"] == "initial_kb":
        val = story["initial_kb"].get(src["key"])
        if not isinstance(val, str) or src["quote"] not in val:
            raise SystemExit("%s: initial_kb quote not found: %s %r" % (
                story["id"], src["key"], src["quote"]))
        return {"kind": "initial_kb", "key": src["key"], "quote": src["quote"]}
    raise SystemExit("unknown source kind: %r" % src)


def build_episode(story):
    turns = []
    pid = PUBLIC_ID[story["id"]]
    for t in story["turns"]:
        case_id = "%s_T%02d" % (pid, len(turns) + 1)
        msgs = [{"role": r, "text": text, "ts": ts} for r, text, ts in t["messages"]]
        inp = {"messages": msgs, "clock": t["clock"],
               "may_decline": bool(t.get("may_decline", False))}
        if t.get("intent"):
            inp["intent"] = dict(t["intent"])
        turns.append({"case_id": case_id, "turn_type": "reply",
                      "input": inp, "gold": {}})
    return {"episode_id": pid,
            "persona": dict(story["persona"]),
            "initial_kb": dict(story["initial_kb"]),
            "turns": turns}


def build_reference(story, episode, facts_by_id):
    turns_by_id = {("%s_T%02d" % (story["id"], i + 1)): t
                   for i, t in enumerate(story["turns"])}
    out = {}
    pid = PUBLIC_ID[story["id"]]
    for i, t in enumerate(story["turns"]):
        case_id = "%s_T%02d" % (pid, i + 1)
        atoms = []
        for fid in t.get("atoms") or []:
            f = facts_by_id[fid]
            atoms.append({
                "atom_id": fid,
                "subject": f["subject"],
                "relation": f["relation"],
                "value": f["value"],
                "valid_time": f["valid_time"],
                "status": f["status"],
                "negation": bool(f["negation"]),
                "source": resolve_fact(story, f, turns_by_id),
                "required_this_turn": fid in (t.get("required") or []),
            })
        out[case_id] = {
            "case_id": case_id,
            "current_action": t["current_action"],
            "acceptable_actions": list(t["acceptable_actions"]),
            "applicable_dimensions": list(t["dims"]),
            "required_memory_atoms": atoms,
            "private_guidance": t["private_guidance"],
            "unknowns": list(t.get("unknowns") or []),
            "protected_expressions": list(t.get("protected") or []),
            "forbidden_factual_claims": list(t.get("forbidden") or []),
            "may_decline": bool(t.get("may_decline", False)),
            "intent": dict(t["intent"]) if t.get("intent") else None,
        }
    return {"kind": "story_reference_v2", "story_id": pid,
            "title": story["title"], "visibility": "evaluator_only",
            "turns": out}


def build_timeline(story, episode):
    msg_index = []
    turn_clocks = []
    for t in episode["turns"]:
        turn_clocks.append({"case_id": t["case_id"], "clock": t["input"]["clock"]})
        for i, m in enumerate(t["input"]["messages"]):
            msg_index.append({
                "case_id": t["case_id"],
                "message_id": "m%d" % i,
                "speaker": m["role"],
                "ts": m["ts"],
                "quote": m["text"],
            })
    revisions = []
    pid = PUBLIC_ID[story["id"]]
    for i, t in enumerate(story["turns"]):
        if t.get("intent"):
            revisions.append({
                "case_id": "%s_T%02d" % (pid, i + 1),
                "kind": "intent",
                "status": t["intent"].get("status"),
                "text": t["intent"].get("text"),
                "enabled": t["intent"].get("enabled"),
            })
    events = []
    for ev in story["events"]:
        e = dict(ev)
        e["source_turn"] = public_case(e["source_turn"])
        events.append(e)
    return {
        "kind": "story_timeline_v2",
        "story_id": pid,
        "timezone": "Asia/Shanghai",
        "turn_clocks": turn_clocks,
        "message_index": msg_index,
        "events": events,
        "relationship": list(story["relationship"]),
        "revisions": revisions,
        "future_policy": "event_time 可以是计划/未来；消息本身不得晚于对应 clock。",
    }


