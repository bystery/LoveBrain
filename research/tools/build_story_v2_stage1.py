def main():
    if not os.path.isdir(OUT_BASE):
        os.makedirs(OUT_BASE, exist_ok=True)
    manifest = {
        "kind": "story_v2_stage1_manifest",
        "date": "2026-10-27",
        "batch": "stage1",
        "count": len(STORIES),
        "turns_per_story": 8,
        "total_positions": len(STORIES) * 8,
        "author": "QoderWork worker-AI (synthetic)",
        "real_user_material": False,
        "validation_claim": False,
        "stories": [],
        "cards_path": "benchmark/stories_v2/stage1/GRADING_CARDS_STAGE1.json",
        "coverage": {
            "themes": sorted(set(t for s in STORIES for t in s["themes"])),
            "has_no_reply": True,
            "has_intent_changes": True,
            "has_callback": True,
            "has_disagreement": True,
            "has_natural_close": True,
        },
    }
    cards = []
    for story in STORIES:
        sid = PUBLIC_ID[story["id"]]
        sdir = os.path.join(OUT_BASE, sid)
        os.makedirs(sdir, exist_ok=True)
        episode = build_episode(story)
        facts_by_id = {f["id"]: f for f in story["facts"]}
        reference = build_reference(story, episode, facts_by_id)
        timeline = build_timeline(story, episode)
        audit = build_audit(story, reference)
        for cid, r in reference["turns"].items():
            cards.append({
                "case_id": cid,
                "current_action": r["current_action"],
                "acceptable_actions": r["acceptable_actions"],
                "applicable_dimensions": r["applicable_dimensions"],
                "required_memory_atoms": r["required_memory_atoms"],
                "private_guidance": r["private_guidance"],
                "unknowns": r["unknowns"],
                "protected_expressions": r["protected_expressions"],
                "forbidden_factual_claims": r["forbidden_factual_claims"],
                "may_decline": r["may_decline"],
            })
        # hashes dict is enough for exposure; turn-level may_decline is separate
        files = {}
        ep_path = os.path.join(sdir, "episode.json")
        ref_path = os.path.join(sdir, "reference.json")
        tl_path = os.path.join(sdir, "timeline.json")
        write_json(ep_path, episode)
        write_json(ref_path, reference)
        write_json(tl_path, timeline)
        with open(os.path.join(sdir, "audit.md"), "w", encoding="utf-8") as f:
            f.write(audit)
        hashes = {"files": {name: sha(path) for name, path in [
            ("episode.json", ep_path), ("reference.json", ref_path),
            ("timeline.json", tl_path), ("audit.md", os.path.join(sdir, "audit.md"))]},
            "turns": reference["turns"]}
        exposure = build_exposure(story, hashes)
        exp_path = os.path.join(sdir, "exposure.json")
        write_json(exp_path, exposure)
        # runner copy
        runner_path = os.path.join(EPISODES, "%s.json" % sid)
        write_json(runner_path, episode)
        if sha(runner_path) != sha(ep_path):
            raise SystemExit("%s runner copy mismatch" % sid)
        manifest["stories"].append({
            "story_id": sid,
            "title": story["title"],
            "themes": story["themes"],
            "turns": len(episode["turns"]),
            "cases": [t["case_id"] for t in episode["turns"]],
            "may_decline_turns": [k for k, v in reference["turns"].items() if v["may_decline"]],
            "intent_revisions": [{"case_id": k, "status": v["intent"]["status"]}
                                 for k, v in reference["turns"].items() if v.get("intent")],
            "atom_count": sum(len(v["required_memory_atoms"]) for v in reference["turns"].values()),
            "required_atom_count": sum(1 for v in reference["turns"].values()
                                       for a in v["required_memory_atoms"]
                                       if a["required_this_turn"]),
            "files": {name: sha(os.path.join(sdir, name)) for name in [
                "episode.json", "reference.json", "timeline.json", "exposure.json", "audit.md"]},
            "runner_copy": "benchmark/episodes/%s.json" % sid,
            "runner_copy_sha256": sha(runner_path),
        })
    write_json(CARDS, cards)
    manifest["cards_sha256"] = sha(CARDS)
    manifest["cards_count"] = len(cards)
    write_json(MANIFEST, manifest)
    print("wrote %d stories to %s" % (len(STORIES), OUT_BASE))
    print("manifest: %s" % MANIFEST)
    print("positions: %d" % manifest["total_positions"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
