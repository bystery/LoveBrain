def build_cards():
    cards = []
    for obj in STORIES:
        ep_name = obj["episode_id"]
        for t in obj["turns"]:
            cid = t["case_id"]
            fam, allowed, failures, contrast, nxt, ambig, guid = CARD_DEFS[cid]
            fam = list(fam)
            # 携带"ME真实发送"标记（该请求窗含 role==ME 的真实历史）
            if any(m["role"] == "ME" for m in t["input"]["messages"]) and "ME真实发送" not in fam:
                fam.append("ME真实发送")
            cards.append({
                "episode_id": ep_name, "case_id": cid, "split": "dev_exposed",
                "content_revision": CONTENT_REVISION,
                "families": fam, "evidence": ev_for(obj, cid),
                "allowed_behaviors": allowed, "failure_conditions": failures,
                "required_reply_phrase": None, "contrast_design": contrast,
                "next_behavior_check": nxt, "unresolved_ambiguities": ambig,
                "review_status": REVIEW_STATUS, "review_guidance": guid,
            })
    return cards


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    ep_path = os.path.join(OUT_DIR, "01_EPISODES_P1.json")
    card_path = os.path.join(OUT_DIR, "02_GRADING_CARDS_P1.json")
    with open(ep_path, "w", encoding="utf-8") as f:
        json.dump(STORIES, f, ensure_ascii=False, indent=1)
    cards = build_cards()
    with open(card_path, "w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=1)
    npos = sum(len(s["turns"]) for s in STORIES)
    print("wrote episodes=%d positions=%d -> %s" % (len(STORIES), npos, ep_path))
    print("wrote cards=%d revision=%s -> %s" % (len(cards), CONTENT_REVISION, card_path))


if __name__ == "__main__":
    main()
