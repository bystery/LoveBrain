    assert len(PAIRS) == 32, f'pairs={len(PAIRS)}'
    fams = {}
    doms = set()
    swap_n = 0
    for p in PAIRS:
        fams[p['category']] = fams.get(p['category'], 0) + 1
        doms.add(p['story'])
        swap_n += 1 if p['swap_probe'] else 0
        # 逐对结构自检：参考先于 judge 的三件套 + 无唯一答案
        r = p['reference']
        assert r['allowed_actions'] and r['forbidden_actions'], p['node_id']
        assert len(r['acceptable_wordings']) >= 2, p['node_id']
        assert len(r['allowed_goal_score_range']) == 2, p['node_id']
        assert p['answers']['甲']['primary'] and p['answers']['乙']['primary'], p['node_id']
        assert p['expected']['relation'] in ('甲better', '乙better', '乙bad_clear', '乙fab', '乙risky', '乙over', 'both_bad', 'tie')
    assert len(fams) >= 6, fams
    assert len(doms) == 3, doms
    assert swap_n == 16, swap_n
    assert len({c['id'] for c in FACT_CLAIMS_BATTERY}) == len(FACT_CLAIMS_BATTERY) >= 20
    assert len({e['id'] for e in PROTECTED_EXPRESSIONS}) == len(PROTECTED_EXPRESSIONS) >= 20
    assert len({c['claim'] for c in FACT_CLAIMS_BATTERY}) == len(FACT_CLAIMS_BATTERY), 'claims must be distinct'

    with open(os.path.join(OUT, 'nodes.jsonl'), 'w', encoding='utf-8') as f:
        for p in PAIRS:
            f.write(json.dumps(p, ensure_ascii=False) + '\n')
    json.dump(FACT_CLAIMS_BATTERY, open(os.path.join(OUT, 'FACT_CLAIMS_BATTERY.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    json.dump(PROTECTED_EXPRESSIONS, open(os.path.join(OUT, 'PROTECTED_EXPRESSIONS.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

