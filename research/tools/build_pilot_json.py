def M(text, ts):
    return {"role": "ME", "text": text, "ts": ts}


def T(case_id, clock, msgs, note="", ttype="normal", intent=None,
      may_decline=False, media=None, hidden=None, delay_note=None):
    t = {"case_id": case_id,
         "input": {"clock": clock, "messages": msgs, "type": ttype}}
    meta = {}
    if note:
        meta["note"] = note
    if intent:
        t["input"]["intent"] = {"enabled": True, "text": intent}
    if may_decline:
        t["input"]["may_decline"] = True
        meta["may_decline"] = True
    if media:
        t["input"]["media"] = media
        meta["media"] = media
    if hidden:
        meta["hidden"] = hidden
    if delay_note:
        meta["delay"] = delay_note
    if meta:
        t["meta"] = meta
    return t


