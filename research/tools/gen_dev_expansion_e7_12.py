def ev_for(ep_obj, case):
    t = next(x for x in ep_obj["turns"] if x["case_id"] == case)
    ev = []
    for i, m in enumerate(t["input"]["messages"]):
        ev.append({"case_id": case, "message_index_zero_based": i,
                   "role": m["role"], "text": m["text"], "ts": m["ts"]})
    if t["input"].get("note"):
        ev.append({"case_id": case, "field": "input.note",
                   "text": t["input"]["note"],
                   "visibility": "private_to_assistant_not_sent"})
    it = t["input"].get("intent") or {}
    if it.get("enabled"):
        ev.append({"case_id": case, "field": "input.intent", "text": it.get("text", ""),
                   "state": "ACTIVE", "visibility": "user_side_goal_may_shape_tone"})
    return ev


