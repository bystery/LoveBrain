def build_cards():
    cards = []
    for ep_name, obj in STORIES.items():
        for t in obj["turns"]:
            cid = t["case_id"]
            fam, allowed, failures, contrast, nxt, ambig, guid = CARD_DEFS[cid]
            cards.append(card(cid, ep_name, fam, ev_for(obj, cid),
                              allowed, failures, contrast, nxt, ambig, guid))
    return cards


def main():
    os.makedirs(EXP_DIR, exist_ok=True)
    for name, obj in STORIES.items():
        with open(os.path.join(EP_DIR, name + ".json"), "w", encoding="utf-8") as f:
            json.dump(obj, f, ensure_ascii=False, indent=1)
        print("wrote episode", name, "turns=%d" % len(obj["turns"]))
    cards = build_cards()
    with open(os.path.join(EXP_DIR, "04_GRADING_CARDS_E007_E012.json"), "w",
              encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=1)
    print("wrote cards=%d revision=%s" % (len(cards), CONTENT_REVISION))


if __name__ == "__main__":
    main()
