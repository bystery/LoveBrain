def T(case, clock, msgs, note=None, may_decline=None, intent=None):
    inp = {"messages": msgs, "clock": clock, "may_decline": bool(may_decline)}
    if note is not None:
        inp["note"] = note
    if intent is not None:
        inp["intent"] = intent
    return {"case_id": case, "turn_type": "reply", "input": inp, "gold": {}}


def M(role, text, ts):
    return {"role": role, "text": text, "ts": ts}


def A(text):   # ACTIVE intent helper
    return {"enabled": True, "text": text, "status": "ACTIVE"}


def OFF(text=""):
    return {"enabled": False, "text": text, "status": "CLOSED"}


