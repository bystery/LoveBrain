import json

def atom(aid, subj, val, rel, status, neg, vtime, key, quote, msg_id='m0', req=False, im=None, gm=None):
    return {'id': aid, 'subject': subj, 'value': val, 'relation': rel, 'status': status,
            'negation': neg, 'valid_time': vtime,
            'source': {'message_id': msg_id, 'key': key, 'quote': quote},
            'affirm_markers': {'item_markers': im or [], 'group_markers': gm or []},
            'required_this_turn': req}

def turn(cid, ca, aa, dims, atoms, pg, unks, pe, ffc, md):
    return {'case_id': cid, 'current_action': ca, 'acceptable_actions': aa,
            'applicable_dimensions': dims, 'required_memory_atoms': atoms,
            'private_guidance': pg, 'unknowns': unks, 'protected_expressions': pe,
            'forbidden_factual_claims': ffc, 'may_decline': md}

def write_ref(eid, turns_data, audit_text):
    ref = {'story_id': eid, 'turns': turns_data}
    path = f'D:/lovebrain-arena_holdout_vault/wave6_holdout/{eid}/reference.json'
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(ref, f, ensure_ascii=False, indent=1)
    apath = f'D:/lovebrain-arena_holdout_vault/wave6_holdout/{eid}/audit.md'
    with open(apath, 'w', encoding='utf-8') as f:
        f.write(audit_text)
    import shutil, hashlib
    sp = f'D:/lovebrain-arena_holdout_vault/wave6_holdout/{eid}/episode.json'
    dp = f'D:/lovebrain-arena_holdout_vault/wave6_holdout/{eid}/runner_episode.json'
    shutil.copy2(sp, dp)
    eh = hashlib.sha256(open(sp,'rb').read()).hexdigest()
    rh = hashlib.sha256(open(dp,'rb').read()).hexdigest()
    print(f'{eid}: ref written, runner hash match={eh==rh}')

